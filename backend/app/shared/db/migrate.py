"""Apply migrations/NNN_name.sql (or .py with run(db)) in order, once each."""
import importlib.util
from pathlib import Path

from . import connect, now
from .config import UPLOAD_DIR

MIGRATIONS = Path(__file__).resolve().parents[4] / "migrations"


def _dialect_sql(sql: str, dialect: str) -> str:
    if dialect == "postgres":
        sql = sql.replace("integer primary key", "bigint generated by default as identity primary key")
        sql = sql.replace("default current_timestamp", "default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')")
    return sql


def migrate() -> None:
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    db = connect()
    try:
        db.script("create table if not exists schema_version (version integer primary key, name text not null, applied_at text)")
        db.commit()
        done = {r[0] for r in db.execute("select version from schema_version").fetchall()}
        for path in sorted([*MIGRATIONS.glob("*.sql"), *MIGRATIONS.glob("[0-9]*.py")]):
            version = int(path.name.split("_", 1)[0])
            if version in done:
                continue
            if path.suffix == ".py":   # runs the module's run(db)
                spec = importlib.util.spec_from_file_location(path.stem, path)
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                module.run(db)
            else:
                db.script(_dialect_sql(path.read_text(encoding="utf-8"), db.dialect))
            db.execute("insert into schema_version (version, name, applied_at) values (?, ?, ?)", (version, path.stem, now()))
            db.commit()
    finally:
        db.close()


def init() -> None:
    migrate()
